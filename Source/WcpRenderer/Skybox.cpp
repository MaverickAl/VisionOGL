namespace
{
	struct FaceProjection
	{
		int   majorAxis;
		float majorSign;
		int   uAxis;
		float uSign;
		int   vAxis;
		float vSign;
	};

	const FaceProjection kFaceProjections[BOX_SIDE_NONE] =
	{
		/* BOX_SIDE_0      */ { 2, -1.0f, 0,  1.0f, 1,  1.0f },
		/* BOX_SIDE_90     */ { 0, -1.0f, 2, -1.0f, 1,  1.0f },
		/* BOX_SIDE_180    */ { 2,  1.0f, 0,  1.0f, 1, -1.0f },
		/* BOX_SIDE_270    */ { 0,  1.0f, 2, -1.0f, 1, -1.0f },
		/* BOX_SIDE_BOTTOM */ { 1, -1.0f, 0,  1.0f, 2, -1.0f },
		/* BOX_SIDE_TOP    */ { 1,  1.0f, 0, -1.0f, 2, -1.0f },
	};
}

